function optimizeMarkup(markup, optimizedAssets) {
  if (!markup || !optimizedAssets || !Object.keys(optimizedAssets).length) return markup;
  return Object.entries(optimizedAssets).reduce((result, [source, target]) => (
    [
      [`../assets/${source}`, `../assets/${target}`],
      [`assets/${source}`, `assets/${target}`],
    ].reduce((next, [from, to]) => next.split(from).join(to), result)
  ), markup);
}
export async function renderDocument({
  rootDir,
  document,
  manifest,
  canonicalBlocks = {},
  optimizedAssets = {},
  templateContext = {},
  shell = {},
}) {
  const read = (relativePath) => readFile(path.join(rootDir, relativePath), 'utf8');
  const optimize = (markup) => optimizeMarkup(markup, optimizedAssets);
  const compile = (markup, source = manifest.id) => markup.replace(/\{\{([A-Z_]+)\}\}/g, (token, key) => {
    if (!(key in templateContext)) throw new Error(`Unknown token ${token} in ${source}`);
    return templateContext[key];
  });
  const fragments = [];
  const sharedParts = manifest.shared ?? {};
  const pageCanonicalBlocks = canonicalBlocks[manifest.id] ?? {};
  const manifestBlocks = manifest.blocks ?? {};

  for (const part of manifest.order) {
    const partMeta = document.parts.find((item) => item.key === part);
    if (!partMeta) throw new Error(`Missing part "${part}" for ${manifest.id}`);
    const source = manifestBlocks[part]
      ?? sharedParts[part]
      ?? pageCanonicalBlocks[part]
      ?? partMeta.file;
    fragments.push(optimize(compile(await read(source), source)));
  }

  let bodyBeforeMain = optimize(compile(document.bodyBeforeMain));
  let mainInner = fragments.join('');
  const restoredInnerPages = new Set(['services', 'projects-clients', 'completed-works', 'contacts']);
  const skipLeadMagnetPages = new Set(['contacts', 'not-found', 'privacy-policy']);
  if (manifest.kind !== 'home') {
    bodyBeforeMain = bodyBeforeMain.replace(/<div\s+data-site-header\s*><\/div>/, optimize(shell.header || ''));
    const contactSlot = /<div\s+data-cta(?:\s+data-title="[^"]*")?\s*><\/div>/g;
    const footerSlot = /<div\s+data-site-footer\s*><\/div>/g;
    const shouldSkipCta = skipLeadMagnetPages.has(manifest.id);
    const hasContactSlot = contactSlot.test(mainInner);
    const hasInlineRequest = /\bdata-inline-request\b/.test(mainInner);
    contactSlot.lastIndex = 0;
    mainInner = mainInner.replace(contactSlot, shouldSkipCta ? '' : optimize(shell.contact || ''));
    if (!hasContactSlot && !hasInlineRequest && footerSlot.test(mainInner)) {
      footerSlot.lastIndex = 0;
      mainInner = mainInner.replace(footerSlot, shouldSkipCta ? optimize(shell.footer || '') : `${optimize(shell.contact || '')}${optimize(shell.footer || '')}`);
    } else {
      footerSlot.lastIndex = 0;
      mainInner = mainInner.replace(footerSlot, optimize(shell.footer || ''));
    }
    if (!restoredInnerPages.has(manifest.id)) mainInner = mainInner.replace(/> Email</g, '> Почта<');
  }
  mainInner = mainInner.replaceAll('mail@ooopdp.ru', 'sale@ooopdp.ru');
  const mainInnerTrailing = optimize(document.mainInnerTrailing);
  const stylesheetPattern = /<link\b(?=[^>]*\brel=(["'])stylesheet\1)[^>]*>/gi;
  const isRedesignedInner = manifest.kind !== 'home' && !restoredInnerPages.has(manifest.id) && !manifest.skipInnerRedesign;
  const shellCacheVersion = '20260930-address-contrast-v8';
  let bodyAfterMainSource = optimize(document.bodyAfterMain)
    .replace(/lenis-scroll\.js\?v=[^\"]+/g, 'lenis-scroll.js?v=20260930-lenis-smooth-v2')
    .replaceAll('mail@ooopdp.ru', 'sale@ooopdp.ru')
    .replace(/production-site-shell\.js\?v=[^\"]+/g, `production-site-shell.js?v=${shellCacheVersion}`);
  if (manifest.id === 'services') {
    bodyAfterMainSource = bodyAfterMainSource.replace(
      /production-services-page\.css\?v=[^\"]+/g,
      'production-services-page.css?v=20260930-form-depth-v10'
    );
    bodyAfterMainSource = bodyAfterMainSource.replace(
      /production-services-hover-polish\.css\?v=[^\"]+/g,
      'production-services-hover-polish.css?v=20260930-sticky-service-v3'
    );
    bodyAfterMainSource = bodyAfterMainSource.replace(
      /production-services-page\.js\?v=[^\"]+/g,
      'production-services-page.js?v=20260930-sticky-service-v2'
    );
  }
  if (manifest.id === 'projects-clients' || manifest.id === 'completed-works') {
    bodyAfterMainSource = bodyAfterMainSource.replace(
      /production-projects-clients-reference\.css\?v=[^\"]+/g,
      'production-projects-clients-reference.css?v=20260930-comparison-height-v13'
    );
    bodyAfterMainSource = bodyAfterMainSource.replace(
      /production-projects-clients-reference\.js\?v=[^\"]+/g,
      'production-projects-clients-reference.js?v=20260930-case-hierarchy-v2'
    );
  }
  if (isRedesignedInner) bodyAfterMainSource = bodyAfterMainSource.replace(/> Email</g, '> Почта<');
  let deferredStyles = bodyAfterMainSource.match(stylesheetPattern) ?? [];
  if (manifest.id === 'contacts') {
    deferredStyles = deferredStyles.map((link) => link.replace(
      /production-contacts-reference\.css\?v=[^\"]+/g,
      'production-contacts-reference.css?v=20260930-map-depth-v6'
    ));
  }
  const bodyAfterMain = bodyAfterMainSource.replace(stylesheetPattern, '').replace(/^[ \t]+$/gm, '');
  const innerMotionPages = new Set(['news-articles', 'service-detail']);
  const innerMotionRuntime = !innerMotionPages.has(manifest.id)
    ? ''
    : '\n  <script src="../shared/vendor/motion-13.2.0.min.js?v=20260911-cache-v10"></script>';
  const innerRedesignStyles = isRedesignedInner
    ? '<link rel="stylesheet" href="../shared/production-inner-redesign-v1.css?v=20260912-inner-redesign-v33">'
    : '';
  const homeServicesLayoutGuard = manifest.kind === 'home'
    ? '<style id="homepage-services-07-layout">@media (min-width:1200px){main.site > .services{min-height:435px;height:auto;}}</style>'
    : '';
  const contactsGutterGuard = (manifest.id === 'contacts' || manifest.id === 'requisites')
    ? '<style id="contacts-desktop-gutters">@media (min-width:1200px){html body.production-contacts main .prod-contact-reference__hero-inner.prod-container{width:100%!important;max-width:none!important;margin-inline:0!important;padding-inline:10vw!important;box-sizing:border-box!important;}body.production-contacts .prod-contact-reference__request>.prod-container{width:80vw!important;max-width:80vw!important;margin-inline:auto!important;}body.production-requisites .prod-requisites-section{width:100%!important;max-width:none!important;margin-inline:0!important;padding-inline:10vw!important;box-sizing:border-box!important;}body.production-requisites .prod-requisites-section>.prod-container{width:100%!important;max-width:none!important;margin-inline:0!important;padding-inline:0!important;}}</style>'
    : '';
  // Keep render-blocking styles in <head>. Some legacy manifests still store
  // these links beside the closing scripts, which otherwise causes a visible
  // first-paint layout shift before the final inner-page geometry arrives.
  let headInnerSource = optimize(compile(document.headInner))
    .replaceAll('https://ooopdp.ru/orig_test_v2/', 'https://ooopdp.ru/')
    .replaceAll('mail@ooopdp.ru', 'sale@ooopdp.ru')
    .replace(/harmonious-production\.css\?v=[^\"]+/g, 'harmonious-production.css?v=20260929-centered-mobile-v15')
    .replace(/shared\/header-shell\.css\?v=[^\"]+/g, 'shared/header-shell.css?v=20260930-address-contrast-v8')
    .replace(/home-motion-polish\.css\?v=[^\"]+/g, 'home-motion-polish.css?v=20260929-compact-mobile-v2')
    .replace(/<link\b(?=[^>]*\brel\s*=\s*(["'])icon\1)[^>]*>\s*/gi, '')
    .replace(/<script\b[^>]*\btype=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>\s*/gi, '');
  headInnerSource = injectPageSeo(headInnerSource, manifest.seo);
  if (manifest.id === 'news-articles') {
    headInnerSource = headInnerSource.replace(
      /production-articles-index-reference\.css\?v=[^\"]+/g,
      'production-articles-index-reference.css?v=20260930-editorial-depth-v3'
    );
  }
  if (manifest.id === 'contacts') {
    headInnerSource = headInnerSource.replace(
      /production-contacts-reference\.css\?v=[^\"]+/g,
      'production-contacts-reference.css?v=20260930-map-depth-v6'
    );
  }
  const pageStyles = (manifest.headStyles ?? [])
    .map((href) => `<link rel="stylesheet" href="${href}">`)
    .join('\n');
  const standardStyles = manifest.kind !== 'home' && manifest.id !== 'contacts'
    ? '<link rel="stylesheet" href="../shared/production-inner-shell-parity.css?v=20260923-site-frame-v2">\n'
    : '';
  const prefix = manifest.kind === 'home' ? '' : '../';
  headInnerSource += `\n<link rel="stylesheet" data-pdp-footer href="${prefix}shared/production-footer-shell.css?v=20260929-footer-grid-stretch-v5">\n`;
  const faviconLinks = [
    `<link rel="icon" href="${prefix}favicon.ico" sizes="any">`,
    `<link rel="icon" href="${prefix}favicon.svg" type="image/svg+xml">`,
    `<link rel="apple-touch-icon" href="${prefix}apple-touch-icon.png">`
  ].join('\n') + '\n';
  const schemaMarkup = generatePageSchemaOrg(manifest, headInnerSource);
  const head = [headInnerSource, faviconLinks, deferredStyles.length ? deferredStyles.join('\n') + '\n' : '', innerRedesignStyles, pageStyles ? `${pageStyles}\n` : '', standardStyles, homeServicesLayoutGuard, contactsGutterGuard, schemaMarkup, GENERATED_MARKER].join('');

  return [
    document.doctype,
    document.htmlOpen,
    '\n',
    document.headOpen,
    head,
    document.headClose,
    '\n',
    document.bodyOpen,
    bodyBeforeMain,
    document.mainOpen,
    mainInner,
    mainInnerTrailing,
    document.mainClose,
    innerMotionRuntime,
    bodyAfterMain,
    document.bodyClose,
    '\n',
    document.htmlClose,
    '\n\r\n\r\n',
  ].join('');
}

