function injectPageSeo(head, seo) {
  if (!seo) return head;
  const escape = (value) => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
  let result = head
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi, '')
    .replace(/<meta\b(?=[^>]*\b(?:name|property)\s*=\s*(["'])(?:description|robots|og:type|og:title|og:description|og:url)\1)[^>]*>\s*/gi, '')
    .replace(/<link\b(?=[^>]*\brel\s*=\s*(["'])canonical\1)[^>]*>\s*/gi, '')
    .replace(/^[\t ]+$/gm, '');
  const tags = [
    `<title>${escape(seo.title)}</title>`,
    `<meta name="description" content="${escape(seo.description)}">`,
    `<meta name="robots" content="${escape(seo.robots ?? 'index,follow')}">`,
    '<meta property="og:type" content="website">',
    `<meta property="og:title" content="${escape(seo.title)}">`,
    `<meta property="og:description" content="${escape(seo.ogDescription ?? seo.description)}">`,
    `<meta property="og:url" content="${escape(seo.canonical)}">`,
    `<link rel="canonical" href="${escape(seo.canonical)}">`,
  ].join('\n');
  return /<link\b/i.test(result) ? result.replace(/<link\b/i, (match) => `${tags}\n${match}`) : `${result}\n${tags}\n`;
}

