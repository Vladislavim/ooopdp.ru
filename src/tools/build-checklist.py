def text(value, x, y, size=11, bold=False, width=495, color=INK):
    style = ParagraphStyle('p', fontName='Bold' if bold else 'Body', fontSize=size,
                           leading=size*1.4, textColor=color)
    p = Paragraph(value, style)
    _, height = p.wrap(width, 700)
    p.drawOn(c, x, y-height)
    return y-height

