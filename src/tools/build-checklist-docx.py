def p(text='', style=None):
    return doc.add_paragraph(text, style)
def label(text):
    x=p(text); x.paragraph_format.space_after=Pt(20)
    x.runs[0].font.size=Pt(9); x.runs[0].bold=True
    x.runs[0].font.color.rgb=RGBColor.from_string('F45116')
def heading(n, title, intro):
    label(f'ПДП   /   РАБОЧИЙ ДОКУМЕНТ   /   {n}')
    p(title,'Heading 1'); p(intro)
def field(title, hint):
    p(title,'Heading 2'); p(hint)
    x=p('[Введите ответ]'); x.runs[0].italic=True
    x.runs[0].font.color.rgb=RGBColor.from_string('747770')
    x.paragraph_format.space_after=Pt(20)
def check(title, detail):
    x=p(); x.paragraph_format.space_after=Pt(12)
    x.add_run('☐  '+title).bold=True
    x.add_run('\n'+detail)
def page(): doc.add_page_break()

